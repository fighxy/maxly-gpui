// Generate crates/max-proto/src/opcode.rs from re/out/opcodes_desktop.tsv (see opcodes.sh).
// Names come from the desktop C++ packet types; only opcodes seen in the desktop binary or in a
// capture are emitted (ADR-002).
// Usage: node gen_opcodes.mjs <opcodes_desktop.tsv> <out.rs>
import { readFileSync, writeFileSync } from "node:fs";

const [tsvPath, outPath] = process.argv.slice(2);

// Opcodes confirmed by a capture but not built with CommonPacket/CommonEvent templates.
const EXTRA = new Map([[1, { name: "Ping", doc: "Keep-alive; client sends `{interactive}` every 30 s (capture cap1)." }]]);

// Readable names where the type path alone gives a poor one. The desktop type stays in the doc.
const OVERRIDES = new Map([
  [18, "Auth"], [19, "Login"], [26, "AssetsGet"], [28, "AssetsGetByIds"],
  [72, "SearchMessageTouch"], [119, "BotSuspend"], [129, "NotificationTyping"],
  [132, "NotificationPresence"], [159, "NotificationProfile"], [163, "CallsHistoryGet"],
  [164, "CallsHistoryClear"], [240, "PinnedMessagesGetStates"], [261, "AssetsListModify"],
  [307, "Unnamed307"],
]);

const strip = (t) => t.replace(/::(Parameters|Payload|Response)$/, "");
const GENERIC = new Set(["Send", "Delete", "Edit", "Get", "Update", "Add", "Remove", "Join", "Reorder",
  "Message", "Chat", "Public", "Common", "Sticker", "StickerSet", "AnimojiSet", "History", "Auth", "Login"]);

const byOp = new Map();
for (const line of readFileSync(tsvPath, "utf8").split(/\r?\n/)) {
  if (!line) continue;
  const [op, kind, req, resp] = line.split("\t");
  const code = Number(op);
  const r = byOp.get(code) ?? { kinds: new Set(), types: [] };
  r.kinds.add(kind);
  const reqName = strip(req);
  const respName = strip(resp);
  if (kind === "event") {
    r.types.push(respName.replace(/^Events::/, ""));
  } else if (reqName !== "EmptyParameters" && reqName !== "Events::NoParameters") {
    r.types.push(reqName);
  } else {
    r.types.push(respName === "EmptyResponse" ? reqName : respName);
  }
  byOp.set(code, r);
}

function pascal(path) {
  // "Auth::OneMe::AuthRequest" -> "AuthRequest"; generic leaf -> "MessagingSend".
  const parts = path.split("::").filter((p) => p !== "OneMe");
  let leaf = parts[parts.length - 1].replace(/Data$/, "");
  if (GENERIC.has(leaf) && parts.length > 1) {
    leaf = parts[parts.length - 2] + leaf;
  }
  return leaf;
}

const entries = [];
for (const [code, r] of [...byOp.entries()].sort((a, b) => a[0] - b[0])) {
  // Prefer a packet type over an event type, and a specific type over EmptyParameters.
  const types = r.types.filter((t) => t !== "EmptyParameters");
  const name = OVERRIDES.get(code) ?? pascal(types[0] ?? r.types[0]);
  entries.push({ code, name, kinds: [...r.kinds].sort().join("+"), types: [...new Set(r.types)] });
}
for (const [code, e] of EXTRA) {
  if (!byOp.has(code)) entries.push({ code, name: e.name, kinds: "capture", types: [], doc: e.doc });
}
entries.sort((a, b) => a.code - b.code);

// Disambiguate duplicate names by suffixing the opcode.
const seen = new Map();
for (const e of entries) seen.set(e.name, (seen.get(e.name) ?? 0) + 1);
for (const e of entries) if (seen.get(e.name) > 1) e.name = `${e.name}${e.code}`;

let rs = `// @generated by re/scripts/gen_opcodes.mjs from the desktop opcode table
// (MAX 26.41.0.83760, \`CommonPacket<opcode, ...>\` / \`CommonEvent<opcode, ...>\` in core.dll).
// Do not edit by hand: regenerate.

/// Packet types the official desktop client knows. Frames keep the raw \`u16\`, so an opcode
/// missing here still passes through [\`crate::Frame\`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
#[repr(u16)]
#[non_exhaustive]
pub enum Opcode {
`;
for (const e of entries) {
  const doc = e.doc ?? `Desktop type${e.types.length > 1 ? "s" : ""}: ${e.types.map((t) => `\`${t}\``).join(", ")} (${e.kinds}).`;
  rs += `    /// ${doc}\n    ${e.name} = ${e.code},\n`;
}
rs += `}

impl Opcode {
    /// Every known opcode, in numeric order.
    pub const ALL: &'static [Opcode] = &[
${entries.map((e) => `        Opcode::${e.name},`).join("\n")}
    ];

    /// The opcode for a raw value, if the desktop client knows it.
    pub const fn from_u16(value: u16) -> Option<Opcode> {
        match value {
${entries.map((e) => `            ${e.code} => Some(Opcode::${e.name}),`).join("\n")}
            _ => None,
        }
    }

    /// The raw wire value.
    pub const fn as_u16(self) -> u16 {
        self as u16
    }
}

impl From<Opcode> for u16 {
    fn from(op: Opcode) -> u16 {
        op.as_u16()
    }
}
`;
writeFileSync(outPath, rs);
console.log(`${entries.length} opcodes written to ${outPath}`);
