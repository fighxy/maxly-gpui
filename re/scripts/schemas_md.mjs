// Render re/out/schemas.tsv (ExtractSchemas.java) as a readable reference.
// Fields of a struct are merged across all constructors that register them, in first-seen order.
// Usage: node schemas_md.mjs <schemas.tsv> <out.md>
import { readFileSync, writeFileSync } from "node:fs";

const [tsvPath, outPath] = process.argv.slice(2);

function splitArgs(s) {
  const out = [];
  let depth = 0;
  let cur = "";
  for (const ch of s) {
    if (ch === "<") depth++;
    if (ch === ">") depth--;
    if (ch === "," && depth === 0) {
      out.push(cur.trim());
      cur = "";
    } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

export function rustType(t) {
  t = t.trim().replace(/^class |^struct /, "").replace(/string_const_/g, "string");
  const m = t.match(/^([A-Za-z_:]+)<(.*)>$/);
  if (m) {
    const [, outer, inner] = m;
    const args = splitArgs(inner);
    switch (outer) {
      case "std::optional":
        return `${rustType(args[0])}?`;
      case "std::vector":
        return args[0].trim() === "std::byte" ? "bytes" : `Vec<${rustType(args[0])}>`;
      case "std::map":
      case "std::unordered_map":
        return `Map<${rustType(args[0])}, ${rustType(args[1])}>`;
      case "std::set":
      case "std::unordered_set":
        return `Set<${rustType(args[0])}>`;
      case "T::Polymorphic":
        return `Polymorphic<${rustType(args[0])}>`;
      default:
        return `${outer}<${args.map(rustType).join(", ")}>`;
    }
  }
  return (
    {
      __int64: "i64",
      "unsigned __int64": "u64",
      int: "i32",
      "unsigned int": "u32",
      short: "i16",
      "unsigned short": "u16",
      char: "i8",
      "unsigned char": "u8",
      bool: "bool",
      double: "f64",
      float: "f32",
      string: "string",
    }[t] ?? t
  );
}

const structs = new Map();
for (const line of readFileSync(tsvPath, "utf8").split(/\r?\n/)) {
  if (!line) continue;
  const [name, , key, type, flag] = line.split("\t");
  const s = structs.get(name) ?? new Map();
  if (!s.has(key)) s.set(key, { type: rustType(type), flags: new Set() });
  if (flag) s.get(key).flags.add(flag);
  structs.set(name, s);
}

const names = [...structs.keys()].sort();
let md = `# Packet and type schemas (MAX desktop 26.41.0.83760)

Generated by \`re/scripts/schemas_md.mjs\` from \`re/ghidra_scripts/ExtractSchemas.java\` over
\`core.dll\`: every struct serialized through \`Serialization::SerializableMember<T, Msgpack, ...,
Struct>\`, with its msgpack keys in registration order (the order the client writes them).
\`P::\` = \`Api::OneMe::Packets::\`, \`T::\` = \`Api::OneMe::Types::\`. \`X?\` is \`std::optional<X>\`
(absent from the map when empty). Integers keep their C++ width on the wire (\`i64\` = msgpack
int64). "flags" is the member flag the constructor writes; its meaning is not decoded yet.

${names.length} structs. Do not edit by hand: regenerate.

`;
for (const name of names) {
  md += `## \`${name}\`\n\n| # | key | type | flags |\n|---:|---|---|---|\n`;
  let i = 0;
  for (const [key, f] of structs.get(name)) {
    md += `| ${i++} | \`${key}\` | \`${f.type}\` | ${[...f.flags].join(",")} |\n`;
  }
  md += "\n";
}
writeFileSync(outPath, md);
console.log(`${names.length} structs, ${[...structs.values()].reduce((n, s) => n + s.size, 0)} fields`);
